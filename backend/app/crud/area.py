async def get_area_id_map(
    session: AsyncSession,
    area_ids: list[str],
) -> dict[str, int]:
    """
    Fetch current areas by functional IDs in a single query (Validation flow Step 2).

    Returns a mapping of {functional_area_id: technical_id} for all current areas
    matching the given IDs. Used for O(1) referential integrity checks in bulk operations.

    Args:
        session: Async database session
        area_ids: List of area functional IDs to look up

    Returns:
        Dictionary mapping functional area_id to technical id
    """
    if not area_ids:
        return {}

    stmt = select(Area.area_id, Area.id).where(
        Area.area_id.in_(area_ids),
        Area.ended_at.is_(None),
    )
    result = await session.execute(stmt)
    return {row[0]: row[1] for row in result.all()}


async def get_area_ca_map(
    session: AsyncSession,
    area_ids: list[str],
) -> dict[str, tuple[int, str, str | None]]:
    """
    Fetch current areas with their competent authority data in a single query.

    Returns a mapping of {functional_area_id: (technical_id, ca_functional_id, ca_name)}
    for all current areas matching the given IDs.

    Args:
        session: Async database session
        area_ids: List of area functional IDs to look up

    Returns:
        Dictionary mapping functional area_id to (technical_id, ca_id, ca_name)
    """
    if not area_ids:
        return {}

    stmt = (
        select(
            Area.area_id,
            Area.id,
            CompetentAuthority.competent_authority_id,
            CompetentAuthority.competent_authority_name,
        )
        .join(CompetentAuthority, Area.competent_authority_id == CompetentAuthority.id)
        .where(
            Area.area_id.in_(area_ids),
            Area.ended_at.is_(None),
        )
    )
    result = await session.execute(stmt)
    return {row[0]: (row[1], row[2], row[3]) for row in result.all()}


async def mark_as_ended(
    session: AsyncSession,
    area_id: str,
    competent_authority_id: int,
) -> None:
    """
    Mark the current version of an area as ended (set ended_at = now()).

    Args:
        session: Async database session
        area_id: Area functional ID
        competent_authority_id: Competent authority technical ID (foreign key)
    """
    stmt = (
        update(Area)
        .where(
            Area.area_id == area_id,
            Area.competent_authority_id == competent_authority_id,
            Area.ended_at.is_(None),
        )
        .values(ended_at=func.now())
    )
    await session.execute(stmt)
    await session.flush()
