BULK_SUMMARY = "Submit activities in bulk for the currently authenticated platform"

BULK_DESCRIPTION = """Submit 1-1000 activities into the activities collection for the currently authenticated platform.

**ID Pattern:**
- `activityId` is **provided by the platform** as a business identifier (optional, currently recommended, in the future required), otherwise it is **generated by SDEP**
- When provided by the platform
  - The recommended `activityId` format is a lowercase UUID (UUIDv4, v5 or v8, RFC 9562).
  - This prevents uniqueness conflicts with other platforms.
  - The reference implementation SDEP-NL (country-specific) also validates the UUID syntax (any other format → item NOK, `business_logic_error`).
- When generated by SDEP
  - The UUID is generated as a deterministic, lowercase UUIDv8 (RFC 9562).
  - This generation is deprecated, but stays supported until UUIDs provided by the platform have become mandatory.
- An `activityId`, whether supplied or generated, remains permanently associated with exactly one platform, to ensure referential integrity
- An `activityId` (from the contract perspective) is currently case-sensitive and preserved exactly as submitted
  - So existing non-UUID identifiers can stay as they are
  - For example, `My3F2A` and `My3f2a` are treated as distinct IDs.
  - In SDEP-NL, a new ID is always a lowercase UUID, so this use case does not apply there.
- A returned `activityId` should always be kept
  - It is needed when wanting to update or correct the activity.

**Versioning:**

| Supplied `activityId` by client     | Activity content        | Result                                                                              |
| ----------------------------------- | ----------------------- | ----------------------------------------------------------------------------------- |
| **New, lowercase UUID**             | New                     | Item OK, new activity **[1]**                                                       |
| New, other format (deprecated)      | New                     | Item OK, new activity, unless taken by another platform (`duplicate_error`) **[2]** |
| **Existing, lowercase UUID**        | Same as before          | Item OK, stored activity **[3]**                                                    |
| **Existing, lowercase UUID**        | Other                   | Item OK, new version (e.g. when `status` is corrected to `cancelled`)               |
| Existing, other format (deprecated) | Same as before          | Item OK, stored activity **[3]**                                                    |
| Existing, other format (deprecated) | Other                   | Item OK, new version (e.g. when `status` is corrected to `cancelled`)               |
| Empty (deprecated)                  | New                     | Item OK, new activity, generated `activityId`                                       |
| Empty (deprecated)                  | Same as before          | Item OK, stored activity **[3]**                                                    |
| Empty (deprecated)                  | Other key **[4]**       | Item OK, new activity, new generated `activityId`                                   |
| Empty (deprecated)                  | Same key, other content | Item OK, new version (a correction, e.g. `numberOfGuests`)                          |

[1] Unless taken by another platform (`duplicate_error`). This is checked for, but with a UUID this practically never happens.

[2] A new ID in another format is not supported by the reference implementation SDEP-NL, only the UUID syntax is accepted (`business_logic_error`).

[3] Same `activityId` and `createdAt` as stored, nothing new is stored (idempotent).

[4] The key is `registrationNumber`, `startDatetime`, `endDatetime` and `url`.

- Two different activities with the same key stay apart only with an own `activityId` each
- Activity content means all fields of the item, except `activityId`
- Equal values count as the same content, e.g. the UTC offset `Z` counts as `+00:00` in a timestamp, an omitted `status` counts as `finished`, and `""`, only spaces or `null` count as an omitted optional field
- Unique constraint: (`activityId`, `createdAt`)
- An item OK counts as succeeded, an item NOK as failed, see **Response HTTP status**

**Validation flow (4 steps):**

1. **Syntax and semantical validation** - each item is validated individually.
   Failed items are marked NOK with the error reason; valid items continue.
2. **Referential Integrity Check** - area IDs are verified. Items with unknown `areaId` are marked NOK; valid items continue.
   Activities are rejected for areas that are regulated for listing only: such items are marked NOK with `regulation_error`.
3. **Bulk Insert** - all remaining valid items are inserted in a single multi-row INSERT.
4. **Feedback** - per-item OK/NOK response preserving original order.

**Intra-batch duplicates (last-wins):**
When the same `activityId` appears multiple times in a single batch, only the last
occurrence is processed. Earlier occurrences receive NOK.

**The request contains:**
- `activities`: Array of activity objects to process (1-1000 items per batch)

**Each activity item in the request contains:**
- `activityId`: Functional ID identifying the activity (optionally supplied: a lowercase UUID RFC 9562 for a new ID, alphanumeric with hyphens `^[A-Za-z0-9\\-]+$`, max 64 chars; auto-generated as deterministic UUIDv8 RFC 9562 if not supplied, deprecated)
- `activityName`: Display name of the activity (optional, max 64 chars)
- `status`: Lifecycle status of the activity. Defaults to `finished` when omitted; may also be `cancelled`
- `areaId`: Functional ID referencing the area where the activity took place
- `url`: URL of the originating listing/advertisement (max 2048 chars)
- `address`: Address composite (`thoroughfare`, `locatorDesignatorNumber` (optional), `locatorDesignatorLetter` (optional), `locatorDesignatorAddition` (optional), `postCode`, `postName`, `fullAddress`)
- `registrationNumber`: Registration number of the address (max 128 chars)
- `numberOfGuests`: Number of guests (1-1024)
- `countryOfGuests`: Array of country codes of guests (1-1024; each element is ISO 3166-1 alpha-3 or `N/A`, uppercase only); array length must equal `numberOfGuests`. One element per guest:
  - Guests from the same country: repeat the code, e.g. 3 guests from the Netherlands give `["NLD", "NLD", "NLD"]`
  - A guest whose country is unknown: `N/A`, e.g. `["NLD", "DEU", "N/A"]`
  - No guest's country known: `N/A` for each guest, e.g. `["N/A", "N/A"]`
- `temporal`: Temporal composite (`startDatetime`, `endDatetime`), both in UTC with offset `Z` or `+00:00` (e.g. `2025-06-01T14:00:00Z`); rejected are other offsets such as CET (`2025-06-01T15:00:00+01:00`), no offset (`2025-06-01T14:00:00`) and no time (`2025-06-01`)

**The response contains:**
- `totalReceived`: Total number of items received in the request
- `succeeded`: Number of items successfully created (status OK)
- `failed`: Number of items that failed validation or processing (status NOK)
- `results`: Per-item results preserving the original request order

**Each results item contains:**
- `activityIndex`: Zero-based index of this item in the original request list
- `activityId`: As supplied in the request item, or `null` when it is missing or not a string
- `status`: Processing result - `OK` (created successfully) or `NOK` (failed validation or processing)
- `activity`: The full activity object (present for OK items, omitted for NOK items)
- `errors`: Structured error details (present for NOK items, omitted for OK items)

**The activity object (for the OK items) contains:**
- `activityId`: Functional ID identifying this activity: as supplied in the request, or generated by SDEP (deterministic UUIDv8) when none was supplied
- `activityName`: Display name (optional) of the activity
- `status`: Lifecycle status of the activity: `finished` or `cancelled`
- `areaId`: Functional ID referencing the area where this activity took place
- `areaName`: Display name (optional) of the area where this activity took place
- `competentAuthorityId`: Functional ID of the competent authority that owns the referenced area
- `competentAuthorityName`: Display name (optional) of the competent authority
- `url`: URL of the originating listing/advertisement
- `address`: Address composite (`thoroughfare`, `locatorDesignatorNumber` (optional), `locatorDesignatorLetter` (optional), `locatorDesignatorAddition` (optional), `postCode`, `postName`, `fullAddress`)
- `registrationNumber`: Registration number of the address (max 128 chars)
- `numberOfGuests`: Number of guests (1-1024)
- `countryOfGuests`: Array of country codes of guests (each element is ISO 3166-1 alpha-3 or `N/A`); array length equals `numberOfGuests`. One element per guest:
  - Guests from the same country: the code repeats, e.g. `["NLD", "NLD", "NLD"]`
  - A guest whose country is unknown: `N/A`, e.g. `["NLD", "DEU", "N/A"]`
- `temporal`: Temporal composite (startDatetime, endDatetime)
- `platformId`: Functional ID referencing the platform that owns the activity
- `platformName`: Display name (optional) of the platform
- `createdAt`: Timestamp when this activity version was created (UTC)

**Response HTTP status:**
- 201: all items created successfully
- 200: partial success (some OK, some NOK)
- 401: missing or invalid token
- 403: insufficient permissions
- 409: a concurrent request wrote the same record first (`conflict_error`), retry the request
- 422: all items failed
"""

